# Comparison report of all solvers from the result files of the three sweep scripts.
#
#   julia --project=. scripts/make_report.jl [--tag spark-bc08] [--dir results] [--out results/REPORT.md]
#
# Reads <dir>/baseline_<tag>.csv (MILP, HiGHS), <dir>/baseline_<tag>_cuopt.csv (MILP, cuOpt; optional)
# and <dir>/heuristics_<tag>.csv (ufp, greedy, best_fit, sjf). Every number in the report is computed
# from these files; the reference of a case is the best proven MILP result of the two solvers.

using Printf

function read_csv(path)
    lines = readlines(path)
    head = split(lines[1], ',')
    return [Dict(zip(head, split(l, ','))) for l in lines[2:end]]
end

int(r, k) = parse(Int, r[k])
flt(r, k) = parse(Float64, r[k])
pct(x) = @sprintf("%+.2f%%", 100x)
upct(x) = @sprintf("%.2f%%", 100x)
mean(v) = sum(v) / length(v)
function median(v)
    e = sort(v)
    return (e[(length(e)+1)÷2] + e[length(e)÷2+1]) / 2
end
secs(x) = x < 0.01 ? @sprintf("%.4f", x) : x < 10 ? @sprintf("%.2f", x) : @sprintf("%.0f", x)

const METHOD_NAMES = ["ufp" => "unsplittable flow", "greedy" => "greedy", "best_fit" => "best fit", "sjf" => "shortest job first"]

function main(args)
    opt = Dict("tag" => "spark-bc08", "dir" => "results", "out" => "")
    for i in 1:2:length(args)
        startswith(args[i], "--") && haskey(opt, args[i][3:end]) && i < length(args) || error("bad option $(args[i])")
        opt[args[i][3:end]] = args[i+1]
    end
    out = isempty(opt["out"]) ? joinpath(opt["dir"], "REPORT.md") : opt["out"]
    highs = read_csv(joinpath(opt["dir"], "baseline_$(opt["tag"]).csv"))
    cu_path = joinpath(opt["dir"], "baseline_$(opt["tag"])_cuopt.csv")
    cuopt = isfile(cu_path) ? read_csv(cu_path) : empty(highs)
    heur = read_csv(joinpath(opt["dir"], "heuristics_$(opt["tag"]).csv"))

    socs = unique(r["soc"] for r in highs)
    widths = sort(unique(int(r, "W") for r in highs))
    tams = sort(unique(int(r, "tams") for r in highs))
    methods = [m for (m, _) in METHOD_NAMES if any(r -> r["method"] == m, heur)]
    label = Dict(METHOD_NAMES)
    cores = Dict(r["soc"] => int(r, "cores") for r in highs)

    key(r) = (String(r["soc"]), int(r, "W"), int(r, "tams"))
    H = Dict(key(r) => r for r in highs)
    C = Dict(key(r) => r for r in cuopt)
    X = Dict((key(r)..., String(r["method"])) => r for r in heur)
    cases = [k for k in sort(collect(keys(H)); by = k -> (findfirst(==(k[1]), socs), k[2], k[3]))
             if all(m -> haskey(X, (k..., m)), methods)]

    # reference per (soc, W, B): best MILP incumbent and best MILP bound of the two solvers
    ref(k) = min(int(H[k], "test_time"), haskey(C, k) ? int(C[k], "test_time") : typemax(Int))
    bnd(k) = max(int(H[k], "bound"), haskey(C, k) ? int(C[k], "bound") : 0)
    proven(k) = bnd(k) >= ref(k) || H[k]["status"] == "OPTIMAL" || (haskey(C, k) && C[k]["status"] == "OPTIMAL")
    time_of(k, m) = int(X[(k..., m)], "test_time")
    best_over_b(f, s, W) = minimum(f(k) for k in cases if k[1] == s && k[2] == W)

    io = IOBuffer()
    println(io, "# ECTSP: comparison of the solvers on the ITC'02 benchmarks\n")
    println(io, "Generated by `scripts/make_report.jl` from the result files of the sweeps on `$(opt["tag"])`",
            " (`baseline_*.csv`, `heuristics_*.csv` in this directory). Test times are in clock cycles.\n")
    println(io, "The check of the MILP and of the core test times against published results is in [PUBLISHED.md](PUBLISHED.md).\n")
    println(io, "## Setup\n")
    println(io, "- Benchmarks: ", length(socs), " ITC'02 SOCs, ", minimum(values(cores)), " to ", maximum(values(cores)),
            " cores with a TAM-applied test (hierarchy flattened, top-level module left out).")
    println(io, "- Total TAM width W = ", join(widths, ", "), "; number of TAMs B = ", join(tams, ", "), ": ",
            length(cases), " cases (SOC, W, B), ", length(socs) * length(widths), " cases (SOC, W) when the best B is taken.")
    println(io, "- Every core has its width to test time Pareto curve from the wrapper design (LPT partition of the scan chains);")
    println(io, "  all solvers see only that table.")
    println(io, "- Solvers:")
    println(io, "  - **MILP**: widths and assignment in one model (JuMP), solved by HiGHS", isempty(cuopt) ? "" : " and by cuOpt",
            ". This is the exact method and the reference below.")
    println(io, "  - **unsplittable flow**: fractional assignment by maximum flow, rounded with the Dinitz-Garg-Goemans algorithm.")
    println(io, "  - **greedy**: longest test first, each core to the TAM on which it finishes earliest.")
    println(io, "  - **best fit**: best fit decreasing into TAMs of capacity C, smallest feasible C by bisection.")
    println(io, "  - **shortest job first**: the greedy rule with the cores in increasing order.")
    println(io, "  The four combinatorial solvers take fixed TAM widths and are run on every partition of W into B widths.\n")

    # ---- MILP status
    println(io, "## MILP reference\n")
    println(io, "| solver | cases | proven optimal | at the time limit | worst remaining gap | total seconds |")
    println(io, "|---|---:|---:|---:|---:|---:|")
    for (name, rows) in (("HiGHS", highs), ("cuOpt", cuopt))
        isempty(rows) && continue
        nopt = count(r -> r["status"] == "OPTIMAL", rows)
        @printf(io, "| %s | %d | %d | %d | %.2f%% | %.0f |\n", name, length(rows), nopt, length(rows) - nopt,
                maximum(flt(r, "gap_pct") for r in rows), sum(flt(r, "seconds") for r in rows))
    end
    open_cases = [k for k in cases if !proven(k)]
    if !isempty(cuopt)
        both = [k for k in cases if haskey(C, k)]
        d = [abs(int(H[k], "test_time") - int(C[k], "test_time")) / ref(k) for k in both]
        println(io, "\nThe two solvers return the same test time in ", count(==(0), d), " of ", length(both),
                " cases; the largest difference is ", upct(maximum(d)), ".")
    end
    if isempty(open_cases)
        println(io, "Every case is proven optimal by at least one solver.")
    else
        println(io, "Not proven optimal by either solver: ",
                join(("$(k[1]) W=$(k[2]) B=$(k[3]) (bound $(bnd(k)), best $(ref(k)), gap $(upct((ref(k) - bnd(k)) / ref(k))))" for k in open_cases), "; "),
                ". For these the reference is the best incumbent, so a negative excess is possible.")
    end

    # ---- main table
    println(io, "\n## Test time with the best number of TAMs\n")
    println(io, "Best B <= ", maximum(tams), " for every method. In brackets: excess over the MILP.\n")
    println(io, "| SOC | cores | W | LB(W) | MILP | ", join((label[m] for m in methods), " | "), " |")
    println(io, "|---|---:|---:|---:|---:|", repeat("---:|", length(methods)))
    excess = Dict(m => Float64[] for m in methods)
    exW = Dict((m, W) => Float64[] for m in methods, W in widths)
    exS = Dict((m, s) => Float64[] for m in methods, s in socs)
    wins = Dict(m => 0 for m in methods)
    hits = Dict(m => 0 for m in methods)
    for s in socs, W in widths
        any(k -> k[1] == s && k[2] == W, cases) || continue
        r = best_over_b(ref, s, W)
        lb = int(H[first(k for k in cases if k[1] == s && k[2] == W)], "lower_bound_W")
        t = Dict(m => best_over_b(k -> time_of(k, m), s, W) for m in methods)
        least = minimum(values(t))
        cells = String[]
        for m in methods
            e = (t[m] - r) / r
            push!(excess[m], e); push!(exW[(m, W)], e); push!(exS[(m, s)], e)
            t[m] == least && (wins[m] += 1)
            t[m] <= r && (hits[m] += 1)
            push!(cells, t[m] <= r ? "**$(t[m])**" : "$(t[m]) ($(pct(e)))")
        end
        println(io, "| $s | $(cores[s]) | $W | $lb | $r | ", join(cells, " | "), " |")
    end
    println(io, "\nBold: the method reaches the MILP test time. LB(W) is the architecture-independent lower bound",
            " (longest core on all W wires, and total wire-cycles divided by W).\n")

    println(io, "### Summary over the ", length(first(values(excess))), " (SOC, W) cases\n")
    println(io, "| method | mean excess | median | worst | reaches the MILP | best of the four |")
    println(io, "|---|---:|---:|---:|---:|---:|")
    for m in methods
        e = excess[m]
        println(io, "| $(label[m]) | $(upct(mean(e))) | $(upct(median(e))) | $(upct(maximum(e))) | $(hits[m]) | $(wins[m]) |")
    end

    println(io, "\n### Mean excess by total width\n")
    println(io, "| method | ", join(("W=$W" for W in widths), " | "), " |")
    println(io, "|---|", repeat("---:|", length(widths)))
    for m in methods
        println(io, "| $(label[m]) | ", join((upct(mean(exW[(m, W)])) for W in widths), " | "), " |")
    end

    println(io, "\n### Mean excess by SOC (over the widths)\n")
    println(io, "| SOC | cores | ", join((label[m] for m in methods), " | "), " |")
    println(io, "|---|---:|", repeat("---:|", length(methods)))
    for s in socs
        println(io, "| $s | $(cores[s]) | ", join((upct(mean(exS[(m, s)])) for m in methods), " | "), " |")
    end

    # ---- fixed B
    println(io, "\n## Fixed number of TAMs\n")
    println(io, "Excess over the MILP with the same W and B (", length(cases), " cases). With one TAM every method is exact.\n")
    println(io, "| method | ", join(("B=$B mean" for B in tams), " | "), " | ", join(("B=$B worst" for B in tams), " | "), " |")
    println(io, "|---|", repeat("---:|", 2 * length(tams)))
    for m in methods
        e(B) = [(time_of(k, m) - ref(k)) / ref(k) for k in cases if k[3] == B]
        println(io, "| $(label[m]) | ", join((upct(mean(e(B))) for B in tams), " | "), " | ",
                join((upct(maximum(e(B))) for B in tams), " | "), " |")
    end
    better = [(k, m) for k in cases for m in methods if time_of(k, m) < ref(k)]
    if !isempty(better)
        println(io, "\nBelow the MILP incumbent (cases at the time limit): ",
                join(("$(label[m]) on $(k[1]) W=$(k[2]) B=$(k[3]) ($(time_of(k, m)) against $(ref(k)))" for (k, m) in better), "; "), ".")
    end

    # ---- run time
    println(io, "\n## Run time\n")
    println(io, "Seconds on `$(opt["tag"])`, summed over the widths and B = ", join(tams, ", "),
            ". The combinatorial solvers include every width partition (1906 partitions for W=64, B=4).\n")
    solvers = vcat(["HiGHS"], isempty(cuopt) ? String[] : ["cuOpt"], [label[m] for m in methods])
    println(io, "| SOC | cores | ", join(solvers, " | "), " |")
    println(io, "|---|---:|", repeat("---:|", length(solvers)))
    tot = zeros(length(solvers))
    for s in socs
        v = Float64[sum(flt(r, "seconds") for r in highs if r["soc"] == s)]
        isempty(cuopt) || push!(v, sum(flt(r, "seconds") for r in cuopt if r["soc"] == s))
        for m in methods
            push!(v, sum(flt(r, "seconds") for r in heur if r["soc"] == s && r["method"] == m))
        end
        tot .+= v
        println(io, "| $s | $(cores[s]) | ", join(secs.(v), " | "), " |")
    end
    println(io, "| **total** | | ", join(("**" * secs(x) * "**" for x in tot), " | "), " |")

    println(io, "\nThe first SOC of a sweep carries the compilation of the solver (visible in the unsplittable flow and greedy columns).")

    # ---- findings (numbers computed above)
    ncase = length(first(values(excess)))
    order = sort(methods; by = m -> mean(excess[m]))
    milp_t = tot[1]
    println(io, "\n## Findings\n")
    println(io, "1. Ranking by mean excess over the MILP with the best B: ",
            join(("$(label[m]) $(upct(mean(excess[m])))" for m in order), ", "), ".")
    println(io, "2. ", uppercasefirst(label[order[1]]), " reaches the MILP test time in ", hits[order[1]], " of ", ncase,
            " cases and is never more than ", upct(maximum(excess[order[1]])), " above it, in ",
            secs(tot[length(solvers)-length(methods)+findfirst(==(order[1]), methods)]), " s against ", secs(milp_t),
            " s of HiGHS for the whole sweep.")
    if "ufp" in methods && "greedy" in methods
        println(io, "3. The unsplittable flow rounding has the only worst-case guarantee of the four (TAM load at most the fractional",
                " load plus one demand; factor 2 for equal TAM widths), but on these SOCs it is behind the two",
                " longest-first heuristics: mean ", upct(mean(excess["ufp"])), ", worst ", upct(maximum(excess["ufp"])),
                ". Its fractional test time is a lower bound for the given widths, which the list heuristics do not provide.")
    end
    if "sjf" in methods
        println(io, "4. Shortest job first is the weakest order: the long tests arrive last and land on loaded TAMs (mean ",
                upct(mean(excess["sjf"])), ", worst ", upct(maximum(excess["sjf"])), ").")
    end
    easy = [s for s in socs if all(m -> m == "sjf" || maximum(exS[(m, s)]) == 0, methods)]
    println(io, "5. SOCs on which every method except shortest job first reaches the MILP at all widths: ", join(easy, ", "),
            ". There the longest core sets the test time (the MILP equals LB(W) at most widths), so any sensible assignment is optimal.")
    println(io, "6. With the number of TAMs fixed the differences are larger than with the best B (table above):",
            " taking the best of B = ", join(tams, ", "), " hides a poor result at one B behind a good one at another.")
    println(io, "7. The MILP is exact but its time grows with the number of cores and the width: ",
            length(open_cases) == 0 ? "all cases closed" : "$(length(open_cases)) of $(length(cases)) cases not closed", " within the time limit; ",
            "HiGHS needed ", secs(milp_t), " s", isempty(cuopt) ? "" : " and cuOpt $(secs(tot[2])) s", " for the ", length(cases), " cases.")

    write(out, take!(io))
    println("wrote $out")
    return 0
end

exit(main(ARGS))
