# Check against published test bus results on d695 and p93791.
#
#   julia -t auto --project=. scripts/compare_published.jl [--time-limit 120] [--out results/PUBLISHED.md]
#
# Sources of the published numbers (testing time in clock cycles, TAM width partition):
#   [ICM]  V. Iyengar, K. Chakrabarty, E.J. Marinissen, "Efficient Wrapper/TAM Co-Optimization for Large SOCs",
#          DATE 2002: Table 2 (a), (c) (d695, results of their earlier exhaustive / ILP method) and
#          Tables 15, 17 (p93791, exhaustive for two TAMs, ILP for three).
#   [KC]   S. Koranne, V.S. Choudhary, "Formulation of SOC Test Scheduling as a Network Transportation Problem",
#          DATE 2002: Table 1 (d695; lpsolve results of Iyengar and Chakrabarty, ETW 2001, and TFLOW).
#
# For every published design the script solves the assignment for the same TAM widths to optimality
# (this compares the core test time tables), and the problem with the same W and number of TAMs.

using ECTSP
using Printf

# (SOC, widths, published testing time)
const ICM = [
    ("d695", [6, 10], 45055), ("d695", [6, 18], 29501), ("d695", [11, 21], 25442), ("d695", [8, 32], 21359),
    ("d695", [16, 32], 19938), ("d695", [19, 37], 18434), ("d695", [20, 44], 18205),
    ("d695", [3, 5, 8], 42568), ("d695", [2, 5, 17], 28292), ("d695", [4, 10, 18], 21566), ("d695", [4, 17, 19], 17901),
    ("d695", [4, 19, 25], 16975), ("d695", [5, 18, 33], 13207), ("d695", [5, 17, 42], 12941),
    ("p93791", [4, 12], 1798740), ("p93791", [1, 23], 1211740), ("p93791", [9, 23], 894342), ("p93791", [17, 23], 747378),
    ("p93791", [2, 46], 622199), ("p93791", [10, 46], 524203), ("p93791", [18, 46], 467424),
    ("p93791", [9, 16, 23], 599373), ("p93791", [10, 23, 23], 514688), ("p93791", [18, 23, 23], 460328),
]

# d695: (W, lpsolve result of [2], TFLOW result, TFLOW partition)
const KC = [
    (16, 42476, 43290, [9, 5, 2]), (20, 34493, 35502, [17, 2, 1]), (24, 28862, 29023, [18, 5, 1]),
    (28, 26964, 24701, [16, 5, 5, 2]), (32, 22945, 21567, [17, 9, 6]), (36, 19858, 19757, [10, 10, 7, 5, 4]),
    (40, 19573, 18799, [12, 12, 7, 5, 4]), (48, 18999, 17210, [19, 19, 6, 4]), (52, 16928, 16084, [32, 8, 6, 6]),
    (56, 15694, 13488, [20, 16, 16, 4]), (60, 15694, 12611, [19, 19, 18, 4]), (64, 15694, 12466, [20, 20, 20, 4]),
]

rel(a, b) = @sprintf("%+.2f%%", 100 * (a - b) / b)
mark(s) = s.status == :OPTIMAL ? "" : "*"

function main(args)
    opt = Dict("time-limit" => "120", "out" => "results/PUBLISHED.md")
    for i in 1:2:length(args)
        startswith(args[i], "--") && haskey(opt, args[i][3:end]) && i < length(args) || error("bad option $(args[i])")
        opt[args[i][3:end]] = args[i+1]
    end
    tl = parse(Float64, opt["time-limit"])
    problems = Dict(n => TestProblem(load_benchmark(n); max_width=64) for n in ("d695", "p93791"))
    io = IOBuffer()
    println(io, "# ECTSP: check against published test bus results\n")
    println(io, "Generated by `scripts/compare_published.jl`. Testing times in clock cycles. `*` marks a MILP run that stopped at")
    println(io, "the time limit of $(opt["time-limit"]) s (best schedule found, not proven optimal).\n")
    println(io, "## Iyengar, Chakrabarty, Marinissen (DATE 2002): d695 and p93791\n")
    println(io, "Published: the exhaustive / ILP results quoted in \"Efficient Wrapper/TAM Co-Optimization for Large SOCs\"")
    println(io, "(Table 2 (a), (c) for d695; Tables 15 and 17 for p93791), fixed-width test buses, two or three TAMs.")
    println(io, "\"Same widths\" is our optimal assignment for the published width partition: it differs from the published")
    println(io, "time only if the core test times differ. \"Same W, B\" is our optimum over all width partitions.\n")
    println(io, "| SOC | W | TAMs | published widths | published | ours, same widths | difference | ours, same W and B | widths | against published |")
    println(io, "|---|---:|---:|---|---:|---:|---:|---:|---|---:|")
    exact = 0
    worst = Dict("d695" => 0.0, "p93791" => 0.0)
    below = 0
    for (n, w, t) in ICM
        p = problems[n]
        s = solve_assignment(p, w; mip_gap=0.0, time_limit=tl)
        b = solve_baseline(p, sum(w), length(w); mip_gap=0.0, time_limit=tl)
        b.makespan > s.makespan && (b = s)
        exact += s.makespan == t
        worst[n] = max(worst[n], abs(s.makespan - t) / t)
        below += b.makespan < t
        println(io, "| $n | $(sum(w)) | $(length(w)) | $(join(w, '+')) | $t | $(s.makespan)$(mark(s)) | ",
                s.makespan == t ? "0" : @sprintf("%+d (%s)", s.makespan - t, rel(s.makespan, t)),
                " | $(b.makespan)$(mark(b)) | $(join(b.widths, '+')) | $(rel(b.makespan, t)) |")
        println(n, " ", join(w, '+'), "  published ", t, "  same widths ", s.makespan, "  same W,B ", b.makespan); flush(stdout)
    end
    println(io, "\n- Same widths: ", exact, " of ", length(ICM), " published times reproduced exactly; largest difference ",
            @sprintf("%.3f%%", 100 * worst["d695"]), " on d695 and ", @sprintf("%.3f%%", 100 * worst["p93791"]), " on p93791.")
    println(io, "  Where they differ ours is the longer one: the core test times come from different wrapper designs")
    println(io, "  (LPT partition of the scan chains here, the best-fit-decreasing `Design_wrapper` there), which can differ by")
    println(io, "  a few scan cells in the longest wrapper chain at some widths.")
    println(io, "- Same W and B: ours is below the published time in ", below, " of ", length(ICM),
            " cases, with a different width partition.\n")

    println(io, "## Koranne, Choudhary (DATE 2002): d695, ILP against TFLOW\n")
    println(io, "Published: Table 1 of \"Formulation of SOC Test Scheduling as a Network Transportation Problem\": the lpsolve")
    println(io, "results of Iyengar and Chakrabarty (ETW 2001; `+` = stopped at 180 minutes) and the unsplittable flow planner")
    println(io, "TFLOW with its width partition. Ours: the solvers of this repository on the TFLOW partition, and the MILP over")
    println(io, "all partitions into the same number of TAMs.\n")
    println(io, "| W | lpsolve [ETW01] | TFLOW | TFLOW partition | ours on that partition: MILP | unsplittable flow | best fit | greedy | ours, same W and B: MILP | widths | against TFLOW |")
    println(io, "|---:|---:|---:|---|---:|---:|---:|---:|---:|---|---:|")
    p = problems["d695"]
    cmp = (opt=0, ufp=0, better=0)
    for (W, ilp, tf, part) in KC
        w = sort(part)
        s = solve_assignment(p, w; mip_gap=0.0, time_limit=tl)
        u = solve_ufp(p, w)
        bf = solve_best_fit(p, w)
        g = solve_greedy(p, w)
        b = solve_baseline(p, W, length(w); mip_gap=0.0, time_limit=tl)
        b.makespan > s.makespan && (b = s)
        cmp = (opt = cmp.opt + (s.makespan <= tf), ufp = cmp.ufp + (u.makespan <= tf), better = cmp.better + (b.makespan < min(ilp, tf)))
        println(io, "| $W | $ilp$(W >= 48 ? "+" : "") | $tf | $(join(part, '+')) | $(s.makespan)$(mark(s)) | $(u.makespan) | $(bf.makespan) | ",
                "$(g.makespan) | $(b.makespan)$(mark(b)) | $(join(b.widths, '+')) | $(rel(b.makespan, tf)) |")
        println("d695 W=", W, "  lpsolve ", ilp, "  TFLOW ", tf, "  ours on partition ", s.makespan, "  ufp ", u.makespan, "  same W,B ", b.makespan); flush(stdout)
    end
    n = length(KC)
    println(io, "\n- On the TFLOW partition our optimal assignment is at or below the TFLOW time in ", cmp.opt, " of ", n,
            " rows and our unsplittable flow solver in ", cmp.ufp, " of ", n, ".")
    println(io, "- Over all partitions with the same number of TAMs our MILP is below both published columns in ", cmp.better, " of ", n, " rows.")
    println(io, "- Where our optimum on the TFLOW partition is above the TFLOW time (W = 32: 21567 is one cycle from the 21566 of")
    println(io, "  the partition 4+10+18 above), the printed partition and time do not fit our core test times; TFLOW predates")
    println(io, "  the ITC'02 files and its core test time table is not available to us.")
    println(io, "- Our unsplittable flow solver is clearly behind TFLOW on these partitions. The paper gives the TAM arc a capacity")
    println(io, "  proportional to its width (T * w_j) and the demand of a core in test bits; `solve_ufp` takes as demand the time")
    println(io, "  on the fastest TAM and gives every TAM the same capacity, which is weak when the widths are very unequal.")
    mkpath(dirname(opt["out"]))
    write(opt["out"], take!(io))
    println("wrote ", opt["out"])
    return 0
end

exit(main(ARGS))
